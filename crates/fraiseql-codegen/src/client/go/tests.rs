/// Go's keywords are all lowercase, so they can only collide with the
/// *unexported* identifiers — parameters — never with an exported field name.
/// A field whose `GraphQL` name does not start with a letter would map to an
/// unexported Go field, which `encoding/json` ignores **silently**; those are
/// prefixed instead.
#[test]
fn identifiers_stay_exported_and_keyword_safe() {
    let mut schema = CompiledSchema::new();
    let mut thing = TypeDefinition::new("Thing", "v_thing");
    thing.fields.push(FieldDefinition::new("id", FieldType::Id));
    thing.fields.push(FieldDefinition::new("_internal", FieldType::String));
    schema.types.push(thing);
    let mut q = QueryDefinition::new("things", "Thing").returning_list();
    q.arguments.push(ArgumentDefinition::new("type", FieldType::String));
    schema.queries.push(q);

    let files = generate(&schema).unwrap();
    let types = file(&files, "types.go");
    assert!(
        types.contains("X_internal string `json:\"_internal\"`"),
        "a non-letter-initial field must still be exported: {types}"
    );

    let queries = file(&files, "queries.go");
    assert!(queries.contains("type_ string"), "keyword param must be escaped: {queries}");
    assert!(
        queries.contains("\"type\": type_,"),
        "the wire key must stay the original GraphQL name: {queries}"
    );
    assert!(queries.contains("$type: String!"), "{queries}");
}

/// A union decodes into the member its `__typename` names; Go has no sum type,
/// so the discriminant is checked in a generated `UnmarshalJSON`.
#[test]
fn unions_decode_by_typename() {
    let mut schema = fixture();
    schema.unions.push(UnionDefinition {
        name:         "CreateUserResult".to_string(),
        description:  None,
        member_types: vec!["User".to_string(), "NotFoundError".to_string()],
    });
    let types = file(&generate(&schema).unwrap(), "types.go");

    assert!(types.contains("type CreateUserResult struct {"), "{types}");
    assert!(types.contains("User          *User          `json:\"-\"`"), "{types}");
    assert!(
        types.contains("func (u *CreateUserResult) UnmarshalJSON(data []byte) error {"),
        "{types}"
    );
    assert!(types.contains("\tcase \"User\":"), "{types}");
    assert!(
        types.contains("return fmt.Errorf(\"unknown __typename %q for union CreateUserResult\""),
        "an unlisted member is an error, not a silent zero value: {types}"
    );
    assert!(types.contains("import (\n\t\"encoding/json\"\n\t\"fmt\"\n)"), "{types}");
}

/// A schema with no decodable union must not emit an import block — an unused
/// import is a **compile error** in Go, so the block is conditional.
#[test]
fn types_file_has_no_imports_without_a_union() {
    let types = file(&generate(&fixture()).unwrap(), "types.go");
    assert!(!types.contains("import ("), "{types}");
}

/// Every pgvector field type renders as the surface it actually has (#959).
///
/// `FieldType` is `#[non_exhaustive]` and defined in another crate, so
/// `field_type_go` must end in a wildcard arm — which is exactly what let
/// `HalfVector` and `SparseVector` degrade to `Any`/`unknown` in the two older
/// generators when they were added. This test is the only thing standing
/// between a newly added variant and a silent `any`.
#[test]
fn every_field_type_maps_to_its_own_surface() {
    for (ft, expected) in [
        (FieldType::String, "string"),
        (FieldType::Id, "string"),
        (FieldType::Uuid, "string"),
        (FieldType::Decimal, "string"),
        (FieldType::DateTime, "string"),
        (FieldType::Date, "string"),
        (FieldType::Time, "string"),
        (FieldType::Scalar("Email".to_string()), "string"),
        (FieldType::Int, "int"),
        (FieldType::Float, "float64"),
        (FieldType::Boolean, "bool"),
        (FieldType::Json, "any"),
        // `[Float!]!` in GraphQL, whatever the column's precision.
        (FieldType::Vector, "[]float64"),
        (FieldType::HalfVector, "[]float64"),
        // Each of these is a string in its own text form: a run of 0/1 for a bit
        // vector, `{1:0.5,7:0.25}/1000` for a sparse one.
        (FieldType::BitVector, "string"),
        (FieldType::SparseVector, "string"),
        (FieldType::List(Box::new(FieldType::String)), "[]string"),
        (FieldType::Object("User".to_string()), "User"),
        (FieldType::Enum("UserRole".to_string()), "UserRole"),
        (FieldType::Input("UserFilter".to_string()), "UserFilter"),
        (FieldType::Interface("Node".to_string()), "Node"),
        (FieldType::Union("Result".to_string()), "Result"),
    ] {
        assert_eq!(field_type_go(&ft), expected, "{ft:?}");
    }
}

/// Slices, maps and `any` already carry `nil`; wrapping them in a pointer would
/// add a second level of absence that no caller wants and JSON cannot express.
#[test]
fn nullability_only_adds_a_pointer_where_go_needs_one() {
    assert_eq!(field_type_go_nullable(&FieldType::Int, true), "*int");
    assert_eq!(field_type_go_nullable(&FieldType::Int, false), "int");
    assert_eq!(field_type_go_nullable(&FieldType::Vector, true), "[]float64");
    assert_eq!(field_type_go_nullable(&FieldType::Json, true), "any");
    assert_eq!(
        field_type_go_nullable(&FieldType::List(Box::new(FieldType::String)), true),
        "[]string"
    );
}

