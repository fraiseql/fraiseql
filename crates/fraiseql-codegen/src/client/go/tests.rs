/// Operations are methods on `*Client` because Go has one exported namespace per
/// package and the canonical `GraphQL` schema collides inside it: a `user` query
/// and a `User` type would be two declarations of the same identifier.
///
/// This is not hypothetical — the canonical conformance fixture has exactly that
/// pair, and as package functions the generated client did not compile.
#[test]
fn an_operation_named_after_a_type_does_not_redeclare_it() {
    let mut schema = CompiledSchema::new();
    let mut user = TypeDefinition::new("User", "v_user");
    user.fields.push(FieldDefinition::new("id", FieldType::Id));
    schema.types.push(user);
    let mut query = QueryDefinition::new("user", "User");
    query.nullable = true;
    query.arguments.push(ArgumentDefinition::new("id", FieldType::Id));
    schema.queries.push(query);

    let files = generate(&schema).unwrap();
    let types = file(&files, "types.go");
    let queries = file(&files, "queries.go");

    assert!(types.contains("type User struct {"), "{types}");
    assert!(
        queries.contains("func (c *Client) User(id string) (*User, error) {"),
        "the operation must be a method, not a package-level `func User`: {queries}"
    );
    assert!(!queries.contains("func User("), "{queries}");
}
