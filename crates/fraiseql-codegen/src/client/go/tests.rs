#[test]
fn required_args_build_a_literal_variables_map() {
    let queries = file(&generate(&fixture()).unwrap(), "queries.go");
    assert!(
        queries.contains("func (c *Client) GetUser(id string) (*User, error) {"),
        "{queries}"
    );
    assert!(
        queries.contains("variables := map[string]any{\n\t\t\"id\": id,\n\t}"),
        "required-only args must be a literal map: {queries}"
    );
    assert!(queries.contains("Result *User `json:\"getUser\"`"), "{queries}");
}

/// A typed nil inside an `any` is not `== nil`, so an optional argument must be
/// omitted by testing the *typed* parameter before boxing it into the map.
/// Filtering after the fact would send `"limit": null` for every unset argument.
#[test]
fn optional_args_are_omitted_before_boxing() {
    let queries = file(&generate(&fixture()).unwrap(), "queries.go");
    assert!(
        queries.contains("func (c *Client) Users(limit *int) ([]User, error) {"),
        "{queries}"
    );
    assert!(
        queries.contains("if limit != nil {\n\t\tvariables[\"limit\"] = limit\n\t}"),
        "optional args must be nil-checked at their typed parameter: {queries}"
    );
    assert!(!queries.contains("omitNil"), "no post-hoc filtering: {queries}");
}

