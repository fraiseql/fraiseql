#[test]
fn required_args_are_inserted_and_optional_ones_omitted() {
    let queries = file(&generate(&fixture()).unwrap(), "queries.rs");
    assert!(queries.contains("pub fn get_user<T: Transport>("), "{queries}");
    assert!(
        queries.contains("    id: String,\n) -> Result<Option<User>, Error> {"),
        "{queries}"
    );
    assert!(queries.contains("var(&mut variables, \"id\", &id)?;"), "{queries}");
    assert!(queries.contains("    limit: Option<i32>,"), "{queries}");
    assert!(
        queries.contains("var_opt(&mut variables, \"limit\", limit.as_ref())?;"),
        "{queries}"
    );
}

/// An unused import is a warning, and the compile gate denies warnings — so the
/// runtime `use` line names only the helpers a file's operations actually call.
#[test]
fn runtime_imports_name_only_what_is_used() {
    let mut schema = CompiledSchema::new();
    let mut thing = TypeDefinition::new("Thing", "v_thing");
    thing.fields.push(FieldDefinition::new("id", FieldType::Id));
    schema.types.push(thing);
    // One query, no arguments at all: neither `var` nor `var_opt` is called.
    schema.queries.push(QueryDefinition::new("things", "Thing").returning_list());

    let queries = file(&generate(&schema).unwrap(), "queries.rs");
    assert!(
        queries.contains("use super::client::{Error, FraiseqlClient, Transport};"),
        "{queries}"
    );
    assert!(!queries.contains("var"), "{queries}");
    assert!(
        queries.contains("client.request(THINGS, serde_json::Map::new(), \"things\")"),
        "{queries}"
    );
}

