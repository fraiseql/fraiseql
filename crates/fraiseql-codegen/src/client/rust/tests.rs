//! Tests for the Rust client generator.
//!
//! Structural assertions on the emitted files. The "does the output compile"
//! direction runs in CI (`sdk-conformance.yml` generates from the canonical
//! conformance fixture and runs `cargo check` with warnings denied) and in
//! `tests/client_rust_consumer.rs`.

#![allow(clippy::unwrap_used, clippy::panic)] // Reason: test code, panics are acceptable

use std::path::PathBuf;

use fraiseql_core::schema::{
    ArgumentDefinition, CompiledSchema, EnumDefinition, EnumValueDefinition, FieldDefinition,
    FieldType, InputFieldDefinition, InputObjectDefinition, MutationDefinition, QueryDefinition,
    TypeDefinition, UnionDefinition,
};

use super::{
    generate,
    render::{field_type_rs, pascal_case, rs_ident, snake_case},
};

fn fixture() -> CompiledSchema {
    let mut schema = CompiledSchema::new();

    let mut user = TypeDefinition::new("User", "v_user");
    user.fields.push(FieldDefinition::new("id", FieldType::Id));
    user.fields.push(FieldDefinition::new("email", FieldType::String));
    let mut display_name = FieldDefinition::new("displayName", FieldType::String);
    display_name.nullable = true;
    user.fields.push(display_name);
    user.fields
        .push(FieldDefinition::new("role", FieldType::Enum("UserRole".to_string())));
    schema.types.push(user);

    let mut not_found = TypeDefinition::new("NotFoundError", "");
    not_found.is_error = true;
    not_found.fields.push(FieldDefinition::new("message", FieldType::String));
    schema.types.push(not_found);

    schema.enums.push(EnumDefinition {
        name:        "UserRole".to_string(),
        values:      vec![
            EnumValueDefinition {
                name:        "ADMIN".to_string(),
                description: None,
                deprecation: None,
            },
            EnumValueDefinition {
                name:        "IN_REVIEW".to_string(),
                description: None,
                deprecation: None,
            },
        ],
        description: None,
    });

    schema
        .input_types
        .push(InputObjectDefinition::new("CreateUserInput").with_fields(vec![
            // Requiredness in the encoding the runtime enforces. A trailing `!`
            // on the type string is resolved into this flag at the compiler seam,
            // so a compiled schema never carries both (#1065).
            InputFieldDefinition::new("email", "String").with_nullable(false),
            InputFieldDefinition::new("role", "UserRole"),
        ]));

    let mut get_user = QueryDefinition::new("getUser", "User");
    get_user.nullable = true;
    get_user.arguments.push(ArgumentDefinition::new("id", FieldType::Id));
    schema.queries.push(get_user);

    let mut users = QueryDefinition::new("users", "User").returning_list();
    let mut limit = ArgumentDefinition::new("limit", FieldType::Int);
    limit.nullable = true;
    users.arguments.push(limit);
    schema.queries.push(users);

    let mut relay = QueryDefinition::new("usersConnection", "User");
    relay.relay = true;
    schema.queries.push(relay);

    let mut create = MutationDefinition::new("createUser", "User");
    create.arguments.push(ArgumentDefinition::new(
        "input",
        FieldType::Input("CreateUserInput".to_string()),
    ));
    schema.mutations.push(create);

    schema
}

fn file(files: &crate::Generated, name: &str) -> String {
    files
        .get(&PathBuf::from(name))
        .unwrap_or_else(|| panic!("missing generated file {name}"))
        .clone()
}

#[test]
fn emits_the_expected_files() {
    let files = generate(&fixture()).unwrap();
    for name in [
        "mod.rs",
        "client.rs",
        "types.rs",
        "enums.rs",
        "inputs.rs",
        "queries.rs",
        "mutations.rs",
    ] {
        assert!(files.contains_key(&PathBuf::from(name)), "missing {name}");
    }
    // No relationships in the fixture → no relationships.rs.
    assert!(!files.contains_key(&PathBuf::from("relationships.rs")));
}

#[test]
fn every_file_is_stamped_with_the_schema_hash() {
    let files = generate(&fixture()).unwrap();
    for (path, content) in &files {
        assert!(
            content.starts_with(
                "// AUTO-GENERATED by fraiseql-codegen. DO NOT EDIT.\n// schema-hash: "
            ),
            "{} is missing the stamp",
            path.display()
        );
    }
}

/// `GraphQL` lets a query and a mutation share a name, so two glob re-exports
/// would hand the consumer an ambiguity at their own use site. Data types are
/// re-exported; operations stay behind `queries::` / `mutations::`.
#[test]
fn the_module_reexports_types_but_not_operations() {
    let module = file(&generate(&fixture()).unwrap(), "mod.rs");
    assert!(module.contains("pub mod queries;"), "{module}");
    assert!(module.contains("pub use types::*;"), "{module}");
    assert!(module.contains("pub use enums::*;"), "{module}");
    assert!(!module.contains("pub use queries::*;"), "{module}");
    assert!(!module.contains("pub use mutations::*;"), "{module}");
}

#[test]
fn objects_are_structs_with_renamed_fields() {
    let types = file(&generate(&fixture()).unwrap(), "types.rs");
    assert!(types.contains("pub struct User {"), "{types}");
    assert!(types.contains("pub id: String,"), "{types}");
    assert!(
        types.contains("#[serde(rename = \"displayName\")]\n    pub display_name: Option<String>,"),
        "snake_cased fields must keep their wire name: {types}"
    );
    assert!(types.contains("pub role: UserRole,"), "{types}");
    assert!(types.contains("use super::enums::UserRole;"), "{types}");
}

/// `serde`'s internally tagged representation strips `__typename` before the
/// variant sees the object, so a union member decoded through the union has no
/// `__typename` field at all — `default` is what keeps that from being an error,
/// and `skip_serializing` keeps the round trip from emitting the tag twice.
#[test]
fn typename_is_defaulted_and_never_re_serialized() {
    let types = file(&generate(&fixture()).unwrap(), "types.rs");
    assert!(
        types.contains("#[serde(rename = \"__typename\", default, skip_serializing)]"),
        "{types}"
    );
}

