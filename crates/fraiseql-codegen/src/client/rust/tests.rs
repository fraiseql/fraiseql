/// A `GraphQL` name that snake-cases onto a Rust keyword must not produce a
/// syntax error — while the wire name stays the original.
#[test]
fn rust_keywords_are_escaped_without_changing_the_wire_shape() {
    let mut schema = CompiledSchema::new();
    let mut thing = TypeDefinition::new("Thing", "v_thing");
    thing.fields.push(FieldDefinition::new("id", FieldType::Id));
    thing.fields.push(FieldDefinition::new("type", FieldType::String));
    schema.types.push(thing);
    let mut q = QueryDefinition::new("things", "Thing").returning_list();
    q.arguments.push(ArgumentDefinition::new("move", FieldType::String));
    schema.queries.push(q);

    let files = generate(&schema).unwrap();
    let types = file(&files, "types.rs");
    assert!(
        types.contains("#[serde(rename = \"type\")]\n    pub type_: String,"),
        "keyword field must be escaped and renamed: {types}"
    );

    let queries = file(&files, "queries.rs");
    assert!(
        queries.contains("    move_: String,"),
        "keyword param must be escaped: {queries}"
    );
    assert!(
        queries.contains("var(&mut variables, \"move\", &move_)?;"),
        "the wire key must stay the original GraphQL name: {queries}"
    );
    assert!(queries.contains("$move: String!"), "{queries}");
}

/// A union is the one place Rust's type system maps onto `GraphQL`'s exactly:
/// an internally tagged enum discriminated by `__typename`.
#[test]
fn unions_are_internally_tagged_enums() {
    let mut schema = fixture();
    schema.unions.push(UnionDefinition {
        name:         "CreateUserResult".to_string(),
        description:  None,
        member_types: vec!["User".to_string(), "NotFoundError".to_string()],
    });
    let types = file(&generate(&schema).unwrap(), "types.rs");
    assert!(types.contains("#[serde(tag = \"__typename\")]"), "{types}");
    assert!(types.contains("pub enum CreateUserResult {"), "{types}");
    assert!(types.contains("    User(User),"), "{types}");
    assert!(types.contains("    NotFoundError(NotFoundError),"), "{types}");
}

/// A union with no members cannot be an enum — an uninhabited type would make
/// every response undecodable. It degrades to the untyped value, as the Python
/// generator's `Any` does.
#[test]
fn empty_unions_degrade_to_a_json_value() {
    let mut schema = fixture();
    schema.unions.push(UnionDefinition {
        name:         "Nothing".to_string(),
        description:  None,
        member_types: Vec::new(),
    });
    let types = file(&generate(&schema).unwrap(), "types.rs");
    assert!(types.contains("pub type Nothing = serde_json::Value;"), "{types}");
}

/// Every pgvector field type renders as the surface it actually has (#959).
///
/// `FieldType` is `#[non_exhaustive]` and defined in another crate, so
/// `field_type_rs` must end in a wildcard arm — which is exactly what let
/// `HalfVector` and `SparseVector` degrade to `Any`/`unknown` in the two older
/// generators when they were added. This test is the only thing standing
/// between a newly added variant and a silent `serde_json::Value`.
#[test]
fn every_field_type_maps_to_its_own_surface() {
    for (ft, expected) in [
        (FieldType::String, "String"),
        (FieldType::Id, "String"),
        (FieldType::Uuid, "String"),
        (FieldType::Decimal, "String"),
        (FieldType::DateTime, "String"),
        (FieldType::Date, "String"),
        (FieldType::Time, "String"),
        (FieldType::Scalar("Email".to_string()), "String"),
        (FieldType::Int, "i32"),
        (FieldType::Float, "f64"),
        (FieldType::Boolean, "bool"),
        (FieldType::Json, "serde_json::Value"),
        // `[Float!]!` in GraphQL, whatever the column's precision.
        (FieldType::Vector, "Vec<f64>"),
        (FieldType::HalfVector, "Vec<f64>"),
        // Each of these is a string in its own text form: a run of 0/1 for a bit
        // vector, `{1:0.5,7:0.25}/1000` for a sparse one.
        (FieldType::BitVector, "String"),
        (FieldType::SparseVector, "String"),
        (FieldType::List(Box::new(FieldType::String)), "Vec<String>"),
        (FieldType::Object("User".to_string()), "User"),
        (FieldType::Enum("UserRole".to_string()), "UserRole"),
        (FieldType::Input("UserFilter".to_string()), "UserFilter"),
        (FieldType::Interface("Node".to_string()), "Node"),
        (FieldType::Union("Result".to_string()), "Result"),
    ] {
        assert_eq!(field_type_rs(&ft), expected, "{ft:?}");
    }
}

#[test]
fn casing_helpers_follow_rust_conventions() {
    assert_eq!(snake_case("displayName"), "display_name");
    assert_eq!(snake_case("postsConnection"), "posts_connection");
    assert_eq!(snake_case("userIDValue"), "user_id_value");
    assert_eq!(snake_case("id"), "id");
    assert_eq!(rs_ident("type"), "type_");
    assert_eq!(pascal_case("IN_PROGRESS"), "InProgress");
    assert_eq!(pascal_case("ADMIN"), "Admin");
    // `SELF` pascal-cases onto the reserved `Self`.
    assert_eq!(pascal_case("SELF"), "Self_");
}

/// A GraphQL input object may reference itself — the derived filter surface puts
/// `_not: OrderWhereInput` on every entity filter (#1154). A Rust struct that
/// holds itself **by value** is infinitely sized, and the generated crate fails
/// to compile with `E0072`, which is what reached CI.
///
/// A `Vec<T>` field is already an indirection, so `_and`/`_or` need no box; only
/// the bare reference does.
#[test]
fn a_self_referential_input_field_is_boxed_but_a_list_of_them_is_not() {
    let mut schema = CompiledSchema::new();
    schema.input_types.push(
        InputObjectDefinition::new("OrderWhereInput")
            .with_field(InputFieldDefinition::new("reference", "StringFilter"))
            .with_field(InputFieldDefinition::new("_and", "[OrderWhereInput!]"))
            .with_field(InputFieldDefinition::new("_not", "OrderWhereInput")),
    );
    schema.input_types.push(
        InputObjectDefinition::new("StringFilter")
            .with_field(InputFieldDefinition::new("eq", "String")),
    );

    let files = generate(&schema).expect("generation succeeds");
    let inputs = files
        .iter()
        .find(|(p, _)| p.ends_with("inputs.rs"))
        .map(|(_, body)| body.clone())
        .expect("inputs.rs is emitted");

    assert!(
        inputs.contains("Option<Box<OrderWhereInput>>"),
        "the self-reference must be boxed or the struct is infinitely sized:\n{inputs}"
    );
    assert!(
        inputs.contains("Option<Vec<OrderWhereInput>>"),
        "a list is already an indirection and must not be boxed:\n{inputs}"
    );
    // A field that cannot reach back to its container stays unboxed — boxing
    // everything would be correct but needlessly awkward to use.
    assert!(
        inputs.contains("Option<StringFilter>"),
        "a non-cyclic input reference must stay unboxed:\n{inputs}"
    );
}

/// Mutual recursion closes the same cycle one hop further out, which a
/// self-reference check alone would miss.
#[test]
fn a_mutually_recursive_input_pair_is_boxed_on_both_sides() {
    let mut schema = CompiledSchema::new();
    schema.input_types.push(
        InputObjectDefinition::new("OrderWhereInput")
            .with_field(InputFieldDefinition::new("customer", "CustomerWhereInput")),
    );
    schema.input_types.push(
        InputObjectDefinition::new("CustomerWhereInput")
            .with_field(InputFieldDefinition::new("primaryOrder", "OrderWhereInput")),
    );

    let files = generate(&schema).expect("generation succeeds");
    let inputs = files
        .iter()
        .find(|(p, _)| p.ends_with("inputs.rs"))
        .map(|(_, body)| body.clone())
        .expect("inputs.rs is emitted");

    assert!(inputs.contains("Option<Box<CustomerWhereInput>>"), "got:\n{inputs}");
    assert!(inputs.contains("Option<Box<OrderWhereInput>>"), "got:\n{inputs}");
}
