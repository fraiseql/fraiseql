#[test]
fn required_args_build_a_plain_variables_dict() {
    let queries = file(&generate(&fixture()).unwrap(), "queries.py");
    assert!(queries.contains("def getUser("), "{queries}");
    assert!(queries.contains("    id: str,"), "{queries}");
    assert!(queries.contains(") -> User | None:"), "{queries}");
    assert!(
        queries.contains("variables = {\"id\": id}"),
        "required-only args must not pass through omit_none: {queries}"
    );
}

#[test]
