//! Tests for the Python client generator.
//!
//! Structural assertions on the emitted files, plus the load-bearing
//! cross-language guarantee: the `GraphQL` documents inside the Python client
//! are byte-identical to the `TypeScript` client's. The "does the output
//! type-check" direction runs in CI (`sdk-conformance.yml` generates from the
//! canonical conformance fixture and runs `ty`/`tsc` on the output).

#![allow(clippy::unwrap_used, clippy::panic)] // Reason: test code, panics are acceptable

use std::path::PathBuf;

use fraiseql_core::schema::{
    ArgumentDefinition, CompiledSchema, EnumDefinition, EnumValueDefinition, FieldDefinition,
    FieldType, InputFieldDefinition, InputObjectDefinition, MutationDefinition, QueryDefinition,
    TypeDefinition,
};

use super::generate;

fn fixture() -> CompiledSchema {
    let mut schema = CompiledSchema::new();

    let mut user = TypeDefinition::new("User", "v_user");
    user.fields.push(FieldDefinition::new("id", FieldType::Id));
    user.fields.push(FieldDefinition::new("email", FieldType::String));
    let mut age = FieldDefinition::new("age", FieldType::Int);
    age.nullable = true;
    user.fields.push(age);
    user.fields
        .push(FieldDefinition::new("role", FieldType::Enum("UserRole".to_string())));
    schema.types.push(user);

    let mut not_found = TypeDefinition::new("NotFoundError", "");
    not_found.is_error = true;
    not_found.fields.push(FieldDefinition::new("message", FieldType::String));
    schema.types.push(not_found);

    schema.enums.push(EnumDefinition {
        name:        "UserRole".to_string(),
        values:      vec![
            EnumValueDefinition {
                name:        "ADMIN".to_string(),
                description: None,
                deprecation: None,
            },
            EnumValueDefinition {
                name:        "MEMBER".to_string(),
                description: None,
                deprecation: None,
            },
        ],
        description: None,
    });

    schema
        .input_types
        .push(InputObjectDefinition::new("CreateUserInput").with_fields(vec![
            InputFieldDefinition::new("email", "String!"),
            InputFieldDefinition::new("role", "UserRole"),
        ]));

    let mut get_user = QueryDefinition::new("getUser", "User");
    get_user.nullable = true;
    get_user.arguments.push(ArgumentDefinition::new("id", FieldType::Id));
    schema.queries.push(get_user);

    let mut users = QueryDefinition::new("users", "User").returning_list();
    let mut limit = ArgumentDefinition::new("limit", FieldType::Int);
    limit.nullable = true;
    users.arguments.push(limit);
    schema.queries.push(users);

    let mut relay = QueryDefinition::new("usersConnection", "User");
    relay.relay = true;
    schema.queries.push(relay);

    let mut create = MutationDefinition::new("createUser", "User");
    create.arguments.push(ArgumentDefinition::new(
        "input",
        FieldType::Input("CreateUserInput".to_string()),
    ));
    schema.mutations.push(create);

    schema
}

fn file(files: &crate::Generated, name: &str) -> String {
    files
        .get(&PathBuf::from(name))
        .unwrap_or_else(|| panic!("missing generated file {name}"))
        .clone()
}

#[test]
fn emits_the_expected_files() {
    let files = generate(&fixture()).unwrap();
    for name in [
        "client.py",
        "types.py",
        "enums.py",
        "inputs.py",
        "queries.py",
        "mutations.py",
        "__init__.py",
    ] {
        assert!(files.contains_key(&PathBuf::from(name)), "missing {name}");
    }
    // No relationships in the fixture → no relationships.py.
    assert!(!files.contains_key(&PathBuf::from("relationships.py")));
}

#[test]
fn every_file_is_stamped_with_the_schema_hash() {
    let files = generate(&fixture()).unwrap();
    for (path, content) in &files {
        assert!(
            content
                .starts_with("# AUTO-GENERATED by fraiseql-codegen. DO NOT EDIT.\n# schema-hash: "),
            "{} is missing the stamp",
            path.display()
        );
    }
}

#[test]
fn objects_are_typed_dicts_with_literal_typename() {
    let types = file(&generate(&fixture()).unwrap(), "types.py");
    assert!(types.contains("class User(TypedDict):"), "{types}");
    assert!(types.contains("__typename: Literal[\"User\"]"), "{types}");
    assert!(types.contains("age: int | None"), "nullable field must be `| None`: {types}");
    assert!(
        types.contains("from .enums import UserRole"),
        "enum leaf refs must be imported: {types}"
    );
}

#[test]
fn error_type_carries_the_injected_status_field() {
    let types = file(&generate(&fixture()).unwrap(), "types.py");
    let error_block = types.split("class NotFoundError").nth(1).expect("NotFoundError emitted");
    assert!(
        error_block.contains("status: str"),
        "error types must carry the runtime-injected status: {types}"
    );
}

