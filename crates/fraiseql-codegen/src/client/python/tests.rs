/// A field or argument named after a Python keyword must not produce a syntax
/// error: fields fall back to the functional `TypedDict` form, parameters get a
/// trailing underscore — while the wire name stays the original.
#[test]
fn python_keywords_are_escaped_without_changing_the_wire_shape() {
    let mut schema = CompiledSchema::new();
    let mut thing = TypeDefinition::new("Thing", "v_thing");
    thing.fields.push(FieldDefinition::new("id", FieldType::Id));
    thing.fields.push(FieldDefinition::new("import", FieldType::String));
    schema.types.push(thing);
    let mut q = QueryDefinition::new("things", "Thing").returning_list();
    q.arguments.push(ArgumentDefinition::new("from", FieldType::String));
    schema.queries.push(q);

    let files = generate(&schema).unwrap();
    let types = file(&files, "types.py");
    assert!(
        types.contains("Thing = TypedDict("),
        "keyword field must force the functional form: {types}"
    );
    assert!(types.contains("\"import\": str"), "{types}");

    let queries = file(&files, "queries.py");
    assert!(queries.contains("from_: str,"), "keyword param must be escaped: {queries}");
    assert!(
        queries.contains("variables = {\"from\": from_}"),
        "the wire key must stay the original GraphQL name: {queries}"
    );
    // The document itself uses the GraphQL name, untouched.
    assert!(queries.contains("$from: String!"), "{queries}");
}

/// The load-bearing shared-core guarantee: the `GraphQL` documents inside the
/// Python and `TypeScript` clients are byte-identical, so the two languages can
/// never drift into different queries.
#[test]
fn documents_are_identical_across_languages() {
    let schema = fixture();
    let py = generate(&schema).unwrap();
    let ts = crate::client::typescript::generate(&schema).unwrap();

    let py_docs = extract_docs(&file(&py, "queries.py"), "\"\"\"", "\"\"\"")
        .into_iter()
        .chain(extract_docs(&file(&py, "mutations.py"), "\"\"\"", "\"\"\""))
        .filter(|d| d.starts_with("query ") || d.starts_with("mutation "))
        .collect::<Vec<_>>();
    let ts_docs = extract_docs(&file(&ts, "queries.ts"), "`", "`")
        .into_iter()
        .chain(extract_docs(&file(&ts, "mutations.ts"), "`", "`"))
        .filter(|d| d.starts_with("query ") || d.starts_with("mutation "))
        .collect::<Vec<_>>();

    assert_eq!(py_docs.len(), 4, "fixture has 3 queries + 1 mutation: {py_docs:?}");
    assert_eq!(py_docs, ts_docs, "Python and TypeScript documents drifted");
}

/// Extract delimited blocks (documents) from generated source.
fn extract_docs(source: &str, open: &str, close: &str) -> Vec<String> {
    let mut docs = Vec::new();
    let mut rest = source;
    while let Some(start) = rest.find(open) {
        let after = &rest[start + open.len()..];
        let Some(end) = after.find(close) else { break };
        docs.push(after[..end].to_string());
        rest = &after[end + close.len()..];
    }
    docs
}
