//! Introspect database for fact tables and output suggestions.
//!
//! This command discovers `tf_*` tables in the database and outputs:
//! - Python suggestions (a `fraiseql.fact_table(...)` call per table)
//! - JSON metadata for manual review
//!
//! **Purpose**: Help developers discover and declare fact tables.
//! **Does NOT auto-modify schema** - outputs suggestions only.

use anyhow::Result;
use fraiseql_core::{
    compiler::fact_table::{DatabaseIntrospector, FactTableDetector, FactTableMetadata, SqlType},
    db::PostgresIntrospector,
};
use serde_json::{Value, json};

use crate::output::OutputFormatter;

/// Output format for introspection results.
#[derive(Debug, Clone, Copy)]
#[non_exhaustive]
pub enum OutputFormat {
    /// Python decorator format
    Python,
    /// JSON format
    Json,
}

impl OutputFormat {
    /// Parse from string
    ///
    /// # Errors
    ///
    /// Returns an error if the string does not match a known output format.
    pub fn parse(s: &str) -> std::result::Result<Self, String> {
        match s.to_lowercase().as_str() {
            "python" | "py" => Ok(Self::Python),
            "json" => Ok(Self::Json),
            _ => Err(format!("Invalid format '{s}', expected: python, json")),
        }
    }
}

/// Create a PostgreSQL introspector from a database URL
async fn create_introspector(database_url: &str) -> Result<PostgresIntrospector> {
    let pool = crate::connection::postgres_pool(
        database_url,
        "fact-table introspection",
        &fraiseql_db::postgres::PostgresTlsConfig::default(),
    )
    .await?;
    Ok(PostgresIntrospector::new(pool))
}

/// Introspect database for fact tables and output suggestions.
///
/// # Arguments
///
/// * `database_url` - Database connection string (e.g., "postgresql://...")
/// * `format` - Output format (Python or JSON)
///
/// # Errors
///
/// Returns an error if the database connection fails or introspection encounters
/// unexpected schema structures.
///
/// # Example
///
/// ```bash
/// fraiseql introspect facts --database postgresql://localhost/mydb --format python
/// ```
pub async fn run(
    database_url: &str,
    format: OutputFormat,
    formatter: &OutputFormatter,
) -> Result<()> {
    formatter.progress("Introspecting database for fact tables...");
    formatter.progress(&format!("   Database: {database_url}"));

    // Create database introspector
    let introspector = create_introspector(database_url).await?;

    // List all fact tables
    let fact_tables = introspector
        .list_fact_tables()
        .await
        .map_err(|e| anyhow::anyhow!("Failed to list fact tables: {e}"))?;

    if fact_tables.is_empty() {
        formatter.progress("\nwarn: No fact tables found (tables starting with 'tf_')");
        formatter.progress("   Fact tables should be named like: tf_sales, tf_events, tf_orders");
        return Ok(());
    }

    formatter.progress(&format!("\nFound {} fact table(s):", fact_tables.len()));
    for table in &fact_tables {
        formatter.progress(&format!("   - {table}"));
    }
    formatter.progress("");

    // Introspect each fact table
    let mut metadata_list: Vec<FactTableMetadata> = Vec::new();
    let mut errors: Vec<(String, String)> = Vec::new();

    for table_name in &fact_tables {
        match FactTableDetector::introspect(&introspector, table_name).await {
            Ok(metadata) => {
                metadata_list.push(metadata);
            },
            Err(e) => {
                errors.push((table_name.clone(), e.to_string()));
            },
        }
    }

    // Report any errors
    if !errors.is_empty() {
        formatter.progress(&format!("warn: Failed to introspect {} table(s):", errors.len()));
        for (table, error) in &errors {
            formatter.progress(&format!("   - {table}: {error}"));
        }
        formatter.progress("");
    }

    // Output results
    match format {
        OutputFormat::Python => {
            println!("\n# Suggested fact table declarations:");
            println!("# (Copy and paste into your Python schema)");
            println!("# Generated by: fraiseql introspect facts");
            println!();
            println!("import fraiseql");
            println!();

            for metadata in &metadata_list {
                println!("{}", format_as_python(metadata));
                println!();
            }
        },
        OutputFormat::Json => {
            let output: serde_json::Value = metadata_list
                .iter()
                .map(|m| {
                    (
                        m.table_name.clone(),
                        json!({
                            "table_name": m.table_name,
                            "measures": m.measures.iter().map(|measure| {
                                json!({
                                    "name": measure.name,
                                    "sql_type": format!("{:?}", measure.sql_type),
                                    "nullable": measure.nullable
                                })
                            }).collect::<Vec<_>>(),
                            "dimensions": {
                                "name": m.dimensions.name,
                                "paths": m.dimensions.paths.iter().map(|p| {
                                    json!({
                                        "name": p.name,
                                        "json_path": p.json_path,
                                        "data_type": p.data_type
                                    })
                                }).collect::<Vec<_>>()
                            },
                            "denormalized_filters": m.denormalized_filters.iter().map(|f| {
                                json!({
                                    "name": f.name,
                                    "sql_type": format!("{:?}", f.sql_type),
                                    "indexed": f.indexed
                                })
                            }).collect::<Vec<_>>(),
                            "calendar_dimensions": m.calendar_dimensions.iter().map(|c| {
                                json!({
                                    "source_column": c.source_column,
                                    "granularities": c.granularities.iter().map(|g| {
                                        json!({
                                            "column_name": g.column_name,
                                            "buckets": g.buckets.iter().map(|b| {
                                                json!({
                                                    "json_key": b.json_key,
                                                    "bucket_type": format!("{:?}", b.bucket_type)
                                                })
                                            }).collect::<Vec<_>>()
                                        })
                                    }).collect::<Vec<_>>()
                                })
                            }).collect::<Vec<_>>()
                        }),
                    )
                })
                .collect::<serde_json::Map<String, serde_json::Value>>()
                .into();

            println!("{}", serde_json::to_string_pretty(&output)?);
        },
    }

    formatter.progress("\nok: Introspection complete");
    formatter.progress(&format!("   {} table(s) introspected successfully", metadata_list.len()));
    if !errors.is_empty() {
        formatter.progress(&format!("   {} table(s) failed", errors.len()));
    }

    Ok(())
}

/// The `sql_type` spelling a schema author writes for `sql_type`, which the compiler reads
/// back as the same [`SqlType`].
fn authored_sql_type(sql_type: &SqlType) -> String {
    let name = match sql_type {
        SqlType::Int => "integer",
        SqlType::BigInt => "bigint",
        SqlType::Decimal => "numeric",
        SqlType::Float => "double precision",
        SqlType::Jsonb => "jsonb",
        SqlType::Json => "json",
        SqlType::Text => "text",
        SqlType::Uuid => "uuid",
        SqlType::TimestampTz => "timestamptz",
        SqlType::LocalTimestamp => "timestamp",
        SqlType::Date => "date",
        SqlType::Boolean => "boolean",
        SqlType::Ltree => "ltree",
        SqlType::Other(name) => name,
        // `SqlType` is `#[non_exhaustive]`: a type added later is spelled as its variant
        // until it is named here.
        other => return format!("{other:?}"),
    };
    name.to_string()
}

/// The keyword arguments of the `fraiseql.fact_table` call that declares `metadata`, as the
/// Python SDK registers them: `measures`, `dimensions` and `denormalized_filters`.
///
/// Calendar dimensions are not among them: the SDK declares none.
pub(crate) fn python_arguments(metadata: &FactTableMetadata) -> Vec<(&'static str, Value)> {
    let measures = metadata
        .measures
        .iter()
        .map(|m| {
            let mut measure = json!({
                "name": m.name,
                "sql_type": authored_sql_type(&m.sql_type),
                "nullable": m.nullable,
            });
            if !m.additivity.is_additive() {
                measure["additivity"] = json!(m.additivity);
            }
            if let Some(column) = &m.column {
                measure["column"] = json!(column);
            }
            measure
        })
        .collect();
    let paths: Vec<Value> = metadata
        .dimensions
        .paths
        .iter()
        .map(|p| json!({"name": p.name, "json_path": p.json_path, "data_type": p.data_type}))
        .collect();
    let filters = metadata
        .denormalized_filters
        .iter()
        .map(|f| {
            let mut filter = json!({
                "name": f.name,
                "sql_type": authored_sql_type(&f.sql_type),
                "indexed": f.indexed,
            });
            if let Some(hierarchy) = &f.hierarchy {
                filter["hierarchy"] = json!(hierarchy);
            }
            filter
        })
        .collect();
    vec![
        ("measures", Value::Array(measures)),
        ("dimensions", json!({"name": metadata.dimensions.name, "paths": paths})),
        ("denormalized_filters", Value::Array(filters)),
    ]
}

/// `value` as a Python literal. A JSON string literal is a Python one, escapes included.
fn python_literal(value: &Value) -> String {
    match value {
        Value::Null => "None".to_string(),
        Value::Bool(true) => "True".to_string(),
        Value::Bool(false) => "False".to_string(),
        Value::Number(_) | Value::String(_) => value.to_string(),
        Value::Array(items) => {
            format!("[{}]", items.iter().map(python_literal).collect::<Vec<_>>().join(", "))
        },
        Value::Object(entries) => format!(
            "{{{}}}",
            entries
                .iter()
                .map(|(key, item)| format!(
                    "{}: {}",
                    Value::from(key.as_str()),
                    python_literal(item)
                ))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

/// The `fraiseql.fact_table(...)` call that declares `metadata` in a Python schema.
///
/// The SDK's `fact_table` is a call, not a decorator: it registers the table and returns
/// nothing. A list argument is written one element per line.
pub(crate) fn format_as_python(metadata: &FactTableMetadata) -> String {
    let mut output = format!(
        "# Fact table: {} ({} measures, {} filters)\nfraiseql.fact_table(\n    {},\n",
        metadata.table_name,
        metadata.measures.len(),
        metadata.denormalized_filters.len(),
        Value::from(metadata.table_name.as_str()),
    );
    for (keyword, value) in python_arguments(metadata) {
        match &value {
            Value::Array(items) if !items.is_empty() => {
                output.push_str(&format!("    {keyword}=[\n"));
                for item in items {
                    output.push_str(&format!("        {},\n", python_literal(item)));
                }
                output.push_str("    ],\n");
            },
            _ => output.push_str(&format!("    {keyword}={},\n", python_literal(&value))),
        }
    }
    output.push(')');
    output
}
